package GUVI_Task1;
// 1. Writ a program to print the numbers from 10 to 50 using for loop / while loop
public class Program1
{
    public static void main(String[] args)
    {
        int numb;

        for (numb=10; numb<=50; numb++)
        {
            System.out.println(numb);
        }

    }
}
